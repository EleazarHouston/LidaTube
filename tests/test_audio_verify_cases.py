@pytest.mark.parametrize("case", CASES, ids=[case["title"][:40] for case in CASES])
def test_real_lookup_verdict(case):
    works = {recording: set(ids) for recording, ids in case["works"].items()}
    verdict = decide(case["title"], case["recording_id"], {"status": "ok", "results": case["results"]},
                     lambda recording: (recording, works.get(recording, set())), expected_artist=case["artist"])
    assert verdict.status == case["expected"], case["why"]
